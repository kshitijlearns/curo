_CONCEPT_OF = {w: c for c, words in CONCEPTS.items() for w in words}


def words(text: str) -> list[str]:
    return [w.strip("'") for w in _WORD.findall((text or "").lower()) if w.strip("'")]


def content_words(text: str) -> list[str]:
    return [w for w in words(text) if w not in STOPWORDS and not w.isdigit()]


def concepts(text: str) -> Counter[str]:
    return Counter(_CONCEPT_OF[w] for w in words(text) if w in _CONCEPT_OF)


def count(pattern: str, text: str) -> int:
    return len(re.findall(pattern, text, flags=re.IGNORECASE))
